"""Build the SpamBlocker import files from rules/<country>/ and write patterns.md.

Usage: python -I tools/build_spamblocker.py
Writes spamblocker/{settings,rules-default,rules-strict,complete}.{gz,json}
and rules/<cc>/patterns.md. Old spamwall-*.{gz,json} files are removed.
"""
import gzip
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "spamblocker"
ALLOW_PRIORITY = 15  # whitelist rules run first
BLOCK_PRIORITY = 5   # never equal to an allow priority (SpamBlocker issue #166)
FLAGS_CALL_AND_SMS = 3
REGEX_FLAGS = 8192


def read_rules(path):
    rules = []
    if not path.exists():
        return rules
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        pattern, _, note = line.partition("#")
        parts = [p.strip() for p in note.split("|")]
        rules.append({
            "pattern": pattern.strip(), "id": parts[0],
            "what": parts[1] if len(parts) > 1 else "",
            "source": parts[2] if len(parts) > 2 else "",
        })
    return rules


def read_dir(path):
    rules = []
    for f in sorted(path.glob("*.txt")):
        rules += read_rules(f)
    return rules


def rule(idx, r, blacklist):
    re.compile(r["pattern"])
    return {
        "id": idx, "pattern": r["pattern"], "patternFlags": REGEX_FLAGS, "patternModeType": 0,
        "patternExtra": "", "patternExtraFlags": 0, "patternExtraModeType": 0,
        "description": f"spamwall {r['id']}: {r['what']}"[:120],
        "priority": BLOCK_PRIORITY if blacklist else ALLOW_PRIORITY,
        "isBlacklist": blacklist, "flags": FLAGS_CALL_AND_SMS, "channel": "Low",
        "schedule": "", "blockType": 0, "blockTypeConfig": "",
    }


def settings(d):
    return {
        "categories": {"all": ["OTHERS"]},
        "contacts": {"enabled": True, "isExcusive": False, "permissivePriority": 10, "strictPriority": 0},
        "stir": {"enabled": True, "includeUnverified": False, "strictPriority": 0},
        "repeatedCall": {"enabled": True, "times": 1, "inXMin": 5},
        "dialed": {"enabled": True, "smsEnabled": True, "always": False, "inXDay": 7},
        "answered": {"warningAcknowledged": True, "enabled": True, "minDuration": 15, "inXDay": 7},
        "recentApps": {"list": [{"pkgName": a["pattern"]} for a in read_rules(d / "allow-apps.txt")], "inXMin": 120},
    }


def rules_part(d, strict):
    allow, block = read_dir(d / "allow"), read_dir(d / "block")
    if strict:
        block += read_dir(d / "optional")
    rules = [rule(i + 100, r, False) for i, r in enumerate(allow)]
    rules += [rule(i + 200, r, True) for i, r in enumerate(block)]
    return {"numberRules": {"rules": rules}}


def files(d):
    s = settings(d)
    default, strict = rules_part(d, False), rules_part(d, True)
    return {
        "settings": s,
        "rules-default": {"categories": {"all": ["REGEX_RULES"]}, **default},
        "rules-strict": {"categories": {"all": ["REGEX_RULES"]}, **strict},
        "complete": {**s, "categories": {"all": ["OTHERS", "REGEX_RULES"]}, **default},
    }


def patterns_md(cc, d):
    esc = lambda t: t.replace("|", "\\|")
    rows = []
    for kind, prio in (("allow", ALLOW_PRIORITY), ("block", BLOCK_PRIORITY), ("optional", BLOCK_PRIORITY)):
        for r in read_dir(d / kind):
            rows.append(f"| {r['id']} | {kind} | `{esc(r['pattern'])}` | {esc(r['what'])} | {esc(r['source'])} | {prio} |")
    head = ("<!-- Generated by tools/build_spamblocker.py. Do not edit. -->\n"
            f"# {cc.upper()} patterns\n\n"
            "| ID | Type | Regex | What | Source | Priority |\n|---|---|---|---|---|---|\n")
    return head + "\n".join(rows) + "\n"


def main():
    OUT.mkdir(exist_ok=True)
    for old in list(OUT.glob("spamwall-*")):
        old.unlink()
    for cc_dir in sorted(p for p in (ROOT / "rules").iterdir() if p.is_dir()):
        for name, obj in files(cc_dir).items():
            data = json.dumps(obj, indent=1, ensure_ascii=False)
            (OUT / f"{name}.json").write_text(data, encoding="utf-8", newline="\n")
            with gzip.GzipFile(OUT / f"{name}.gz", "wb", mtime=0) as f:
                f.write(data.encode("utf-8"))
            print("built", name)
        (cc_dir / "patterns.md").write_text(patterns_md(cc_dir.name, cc_dir), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
